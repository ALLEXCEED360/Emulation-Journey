//! The built-in CHIP-8 font: sprites for the hex digits 0–F.

/// Where the font lives in memory. Any address below 0x200 works; 0x050 is the usual choice.
pub const FONT_START: usize = 0x050;

/// Each character is 5 bytes: 5 rows of 8 pixels (only the left 4 are used).
pub const BYTES_PER_CHAR: usize = 5;

/// Sprite data for 0, 1, 2, … F, one character after another.
pub const FONT: [u8; 16 * BYTES_PER_CHAR] = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80, // F
];

#[cfg(test)]
mod tests {
    use super::*;
    use crate::PROGRAM_START;

    #[test]
    fn font_fits_below_program_start() {
        const { assert!(FONT_START + FONT.len() <= PROGRAM_START) };
    }

    #[test]
    fn zero_is_drawn_as_a_box() {
        assert_eq!(&FONT[0..5], &[0xF0, 0x90, 0x90, 0x90, 0xF0]);
    }
}
